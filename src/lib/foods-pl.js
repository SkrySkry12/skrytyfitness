const fold = s => String(s || "").toLocaleLowerCase("pl-PL").normalize("NFD").replace(/[\u0300-\u036f]/g, "").replace(/ł/g, "l");

export const LOCAL_FOODS = RAW.map(([name, kcal, protein, carbs, fat, servingGrams, servingSize, words], i) => ({
  id: "local-" + i, name, brand: null, kcal, protein, carbs, fat, servingGrams, servingSize,
  complete: true, image: null, source: "Baza podstawowa", local: true,
  _hay: fold(name + " " + (words || ""))
}));

/** Instant offline search: every query word (≥2 chars, crude stem) must appear in name/aliases. */
export function searchLocalFoods(query, limit = 6) {
  const words = fold(query).split(/\s+/).filter(w => w.length >= 2 && !["z", "ze", "w", "na", "i", "do"].includes(w))
    .map(w => w.length > 5 ? w.slice(0, Math.max(5, w.length - 2)) : w);
  if (!words.length) return [];
  return LOCAL_FOODS
    .map(f => {
      if (!words.every(w => f._hay.includes(w))) return null;
      const nameFold = fold(f.name);
      return { f, score: (nameFold.startsWith(words[0]) ? 10 : 0) + words.filter(w => nameFold.includes(w)).length * 3 - nameFold.length / 50 };
    })
    .filter(Boolean)
    .sort((a, b) => b.score - a.score)
    .slice(0, limit)
    .map(x => x.f);
}
